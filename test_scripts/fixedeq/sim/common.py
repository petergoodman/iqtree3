"""Shared pieces of SIM-1's drivers (CODE_PLAN.md 3.8): run directories, provenance, the results.json
and report.md writer, and pi*'s committed file. reference.py's versions hard-code its own script,
seed, label and workers, so they are generalized here rather than reused.

  python test_scripts/fixedeq/sim/common.py target --git git.exe [--allow-dirty]

target writes sim/target.txt once from oracle.simulate.target(): '# key: value' provenance lines,
then pi* as 20 comma-separated values at 17 significant digits, as NQC+F{...} takes them. It never
overwrites the file.
"""
import argparse
import datetime
import json
import platform
import sys
from pathlib import Path

import numpy as np
import scipy

HERE = Path(__file__).resolve().parent
for _p in ("", "regression"):
    sys.path.insert(0, str(HERE.parent / _p))
from oracle import simulate  # noqa: E402
from regress import REPO, capture, read, write  # noqa: E402

SCRIPT = Path(__file__).resolve().relative_to(REPO).as_posix()
TARGET = HERE / "target.txt"
RUNS = Path("~/iqtree3-runs/sim1")


def target_text(path=TARGET):
    """pi* as committed: the file's one data line."""
    lines = [line.strip() for line in read(path).splitlines() if line.strip() and not line.startswith("#")]
    if len(lines) != 1:
        raise ValueError(f"{path}: expected one data line, found {len(lines)}")
    return lines[0]


def target_values(path=TARGET):
    return np.array([float(v) for v in target_text(path).split(",")])


def provenance(a, script, step, label, **extra):
    """Refuses an unclean tree unless a.allow_dirty."""
    commit = capture(a.git, "rev-parse", "HEAD", cwd=REPO)
    clean = capture(a.git, "status", "--porcelain", cwd=REPO) == ""
    if not clean and not a.allow_dirty:
        sys.exit(f"the repository is not clean ({commit}); commit first or pass --allow-dirty")
    return {"script": script, "step": step, "label": label, "command": sys.argv,
            "started_utc": datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds"),
            "git_commit": commit, "git_clean": clean, "python": sys.version, "numpy": np.__version__,
            "scipy": scipy.__version__, "platform": platform.platform(), **extra}


def new_out(path, prov, runs=RUNS):
    """path, or by default runs/<YYYYmmddTHHMMSSZ>-<commit8>-<step>; new and outside the repository."""
    if path is None:
        stamp = datetime.datetime.fromisoformat(prov["started_utc"]).strftime("%Y%m%dT%H%M%SZ")
        path = Path(runs) / f"{stamp}-{prov['git_commit'][:8]}-{prov['step']}"
    out = Path(path).expanduser().resolve()
    if out.exists() or out.is_relative_to(REPO):
        sys.exit(f"{out}: needs a new directory outside the repository")
    out.mkdir(parents=True)
    prov["out"] = str(out)
    return out


def _json(v):
    if isinstance(v, np.ndarray):
        return v.tolist()
    if isinstance(v, (np.floating, np.integer, np.bool_)):
        return v.item()
    return str(v)


def finish(out, prov, title, results, extra=None):
    """Write results.json and report.md and exit, 1 if any asserted row (passed False) failed."""
    prov["finished_utc"] = datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds")
    failed = save(out, prov, title, results, extra)
    for f in failed:
        print(f"  FAIL {f}")
    print(f"{len(failed)} asserted checks failed; wrote {out / 'report.md'}")
    sys.exit(1 if failed else 0)


def save(out, prov, title, results, extra=None):
    """Write results.json and report.md (also part-way through a run); returns the failed checks."""
    write(out / "results.json", json.dumps({"provenance": prov, "results": results, **(extra or {})}, indent=1,
                                           default=_json))
    lines = [f"# {title}", "", f"{prov['label'].capitalize()}. Generated by `{prov['script']}` ({prov['step']}) on "
             f"{prov['started_utc']} at commit `{prov['git_commit']}` (clean: {prov['git_clean']}).", "",
             "| Check | Result | Values |", "|---|---|---|"]
    for row in results:
        verdict = {True: "pass", False: "FAIL", None: "report"}[row["passed"]]
        values = {k: v for k, v in row.items() if k not in ("check", "passed")}
        lines.append(f"| {row['check']} | {verdict} | `{json.dumps(values, default=_json)[:700]}` |")
    write(out / "report.md", "\n".join(lines) + "\n")
    return [row["check"] for row in results if row["passed"] is False]


def cmd_target(a):
    if TARGET.exists():
        sys.exit(f"{TARGET} exists; derived data are never regenerated in place")
    prov = provenance(a, SCRIPT, "target", "derived data")
    header = {"content": "pi*, NQ.bird's stationary distribution (CODE_PLAN.md 3.8; decision 040), "
                         "oracle.simulate.target()",
              "format": "one line of 20 values in IQ-TREE's state order ARNDCQEGHILKMFPSTWYV, comma-separated "
                        "at 17 significant digits, as NQC+F{...} takes them",
              "script": SCRIPT, "git_commit": prov["git_commit"], "git_clean": prov["git_clean"],
              "generated_utc": prov["started_utc"], "python": platform.python_version(),
              "numpy": np.__version__, "scipy": scipy.__version__}
    text = "".join(f"# {k}: {v}\n" for k, v in header.items())
    write(TARGET, text + ",".join(f"{v:.17g}" for v in simulate.target()) + "\n")
    print(f"wrote {TARGET}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="step", required=True)
    t = sub.add_parser("target")
    t.add_argument("--git", default="git")
    t.add_argument("--allow-dirty", action="store_true")
    a = ap.parse_args()
    cmd_target(a)


if __name__ == "__main__":
    main()
