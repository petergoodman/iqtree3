#!/usr/bin/env python3
"""Fit records of nqcchecks.py runs, read back from their saved output (PLAN.md, S2's current state).

  python fitrecords.py NQC_OUT [NQC_OUT ...] --out DIR [--git git.exe] [--allow-dirty]

Each NQC_OUT is an --out directory of nqcchecks.py. For every verbose fit run in it, this reports
what the fits and short cases of nqcchecks.py at 35d4a1bf read wrongly:
- under -v each fit's record is printed twice, by the class and by IQ-TREE's round loop
  (model/modelfactory.cpp:1678-1680), so fits are counted as distinct records;
- residuals and bound counts are taken over every record, not from the last one, which on the
  +I+G path belongs to the last start rather than to the model IQ-TREE restores (decision 033);
- the model the run ended with is read from the class's checkpoint: its bound counts, and its
  residuals as the oracle computes them from the checkpointed coordinates.
A run at default verbosity prints only its last record, so only runs given -v or -vv are read.
Nothing is run; every file read is listed with its SHA-256.
"""
import argparse
import datetime
import json
import platform
import re
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import nqcchecks as nc  # noqa: E402  (also puts the oracle and the other drivers on the path)
from oracle import chart  # noqa: E402
from probes import PREFIX, Run  # noqa: E402
from regress import REPO, SCALARS, capture, sha256, write  # noqa: E402

SCRIPT = Path(__file__).resolve().relative_to(REPO).as_posix()
FALL = r"(?:NQC fit \d+: the re-scored lnL is below the start by \S+ \(reported, not restored\)\n)?"
RECORD = re.compile(nc.FIT.pattern + r"\n" + FALL + nc.BOUNDS.pattern + r"\n" + nc.RESIDUALS.pattern, re.M)


def records(text):
    """Each fit record once, in order of first appearance: (start, optimizer, re-scored) lnL,
    (lower, upper, outside) bound counts, and (stationarity, row sums, mean rate, nu, minimum rate)."""
    unique = list(dict.fromkeys(RECORD.findall(text)))
    return ([tuple(float(v) for v in r[1:4]) for r in unique], [tuple(int(v) for v in r[4:7]) for r in unique],
            [tuple(float(v) for v in r[7:12]) for r in unique])


def bound_counts(z, lower, upper):
    return int(np.sum(z == lower)), int(np.sum(z == upper)), int(np.sum((z < lower) | (z > upper)))


def summarize(run, inputs):
    text, ck = run.stdout(), nc.nqc_checkpoint(run)
    for p in (run.dir / "stdout.txt", run.file(".ckp.gz"), run.file(".iqtree")):
        inputs[str(p)] = sha256(p)
    lnl, bounds, res = (np.array(a) for a in records(text))
    z, (lower, upper) = nc.floats(ck["coordinates"]), nc.floats(ck["domain"])
    pi, ref = nc.floats(ck["target"]), [int(v) for v in ck["references"].split(",")]
    Q, nu = chart.build(z, pi, ref)
    d = chart.diagnostics(Q, pi, nu)
    out = {
        "fit_lines_printed": len(nc.FIT.findall(text)),
        "fits": len(lnl),
        "below_start": int(np.sum(lnl[:, 2] < lnl[:, 0])),
        "largest_over_records": {"stationarity": res[:, 0].max(), "row_sums": res[:, 1].max(),
                                 "mean_rate": res[:, 2].max(), "nu": res[:, 3].max()},
        "smallest_minimum_rate": res[:, 4].min(),
        "upper_bound_range": [int(bounds[:, 1].min()), int(bounds[:, 1].max())],
        "lower_bound_max": int(bounds[:, 0].max()),
        "outside_max": int(bounds[:, 2].max()),
        "last_record": {"bounds": bounds[-1].tolist(), "residuals": res[-1, :3].tolist()},
        "final": {"bounds_lower_upper_outside": list(bound_counts(z, lower, upper)),
                  "accepted_score": float(ck["accepted_score"]),
                  "oracle_residuals": {k: d[k] for k in ("stationarity", "row_sums", "mean_rate_error",
                                                         "nu_residual", "min_rate")}},
        "last_fit_gain": float(lnl[-1, 2] - lnl[-1, 0]),
        "scaling_squaring": text.count(nc.SWITCH),
    }
    printed = re.search(SCALARS["log_likelihood"], run.report(), re.M)
    if printed:
        out["final"]["printed_score"] = float(printed.group(1))
        out["final"]["accepted_minus_printed"] = out["final"]["accepted_score"] - float(printed.group(1))
    return out


def markdown(prov, results):
    lines = ["# Fit records of nqcchecks.py runs", "",
             f"Generated by `{SCRIPT}` on {prov['started_utc']} at commit `{prov['git_commit']}` "
             f"(clean: {prov['git_clean']}).", ""]
    for name, s in results.items():
        f, top = s["final"], s["largest_over_records"]
        lines += [f"## {name}", "",
                  f"- fits {s['fits']} ({s['fit_lines_printed']} fit lines printed); below their start "
                  f"{s['below_start']}; last fit gained {s['last_fit_gain']:.6g}",
                  f"- largest over all records: |pi*Q| {top['stationarity']:.2g}, row sums {top['row_sums']:.2g}, "
                  f"|mean rate - 1| {top['mean_rate']:.2g}, nu {top['nu']:.2g}; smallest rate "
                  f"{s['smallest_minimum_rate']:.3g}",
                  f"- coordinates at the upper bound {s['upper_bound_range'][0]} to {s['upper_bound_range'][1]} over "
                  f"records; at the lower bound at most {s['lower_bound_max']}; outside at most {s['outside_max']}",
                  f"- last record: bounds (lower, upper, outside) {s['last_record']['bounds']}",
                  f"- model the run ended with (checkpoint): bounds {f['bounds_lower_upper_outside']}; oracle "
                  f"residuals " + ", ".join(f"{k} {v:.2g}" for k, v in f["oracle_residuals"].items()),
                  f"- accepted score {f['accepted_score']!r}"
                  + (f"; printed {f['printed_score']!r}, accepted minus printed {f['accepted_minus_printed']:.6g}"
                     if "printed_score" in f else ""),
                  f"- scaling-squaring switches {s['scaling_squaring']}", ""]
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("nqc_out", nargs="+", help="--out directories of nqcchecks.py")
    ap.add_argument("--out", required=True, help="new directory outside the repository")
    ap.add_argument("--git", default="git", help="git executable (git.exe under WSL)")
    ap.add_argument("--allow-dirty", action="store_true")
    a = ap.parse_args()
    out = Path(a.out).expanduser().resolve()
    if out.exists() or out.is_relative_to(REPO):
        sys.exit(f"{out}: needs a new directory outside the repository")
    prov = {"script": SCRIPT, "script_sha256": sha256(Path(__file__)), "command": sys.argv,
            "started_utc": datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds"),
            "git_commit": capture(a.git, "rev-parse", "HEAD", cwd=REPO),
            "git_clean": capture(a.git, "status", "--porcelain", cwd=REPO) == "",
            "python": sys.version, "numpy": np.__version__, "platform": platform.platform(), "inputs": {}}
    if not prov["git_clean"] and not a.allow_dirty:
        sys.exit(f"the repository is not clean ({prov['git_commit']}); commit first or pass --allow-dirty")
    results = {}
    for d in (Path(p).expanduser().resolve() for p in a.nqc_out):
        prov["inputs"][str(d / "results.json")] = sha256(d / "results.json")
        for rec in json.loads((d / "results.json").read_text())["runs"]:
            if rec["exit_code"] == 0 and {"-v", "-vv"} & set(rec["args"]) and (d / rec["name"] / f"{PREFIX}.ckp.gz").exists():
                run = Run(d / rec["name"], rec["name"], rec["args"], rec["exit_code"], rec["wall_s"])
                results[f"{d.parent.name}/{d.name}/{rec['name']}"] = summarize(run, prov["inputs"])
    out.mkdir(parents=True)
    write(out / "results.json", json.dumps({"provenance": prov, "results": results}, indent=1, default=float))
    write(out / "results.md", markdown(prov, results))
    print(f"{len(results)} runs; wrote {out / 'results.md'}")


if __name__ == "__main__":
    main()
